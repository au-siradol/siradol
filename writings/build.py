"""Rebuild the WRITINGS section of index.html from writings/data.json.

Run from the repo root:  python3 writings/build.py
Only the part between the writings:start / writings:end markers is replaced.
"""
import datetime
import html
import itertools
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
URL = re.compile(r'(https?://[^\s]+)')


def para(text):
    out, last = [], 0
    for m in URL.finditer(text):
        out.append(html.escape(text[last:m.start()]))
        url = m.group(1)
        if '...' in url:  # Facebook shortened this link; the real address is unknown
            out.append(html.escape(url))
        else:
            out.append(f'<a href="{html.escape(url)}" rel="noopener">{html.escape(url)}</a>')
        last = m.end()
    out.append(html.escape(text[last:]))
    return '<p>' + ''.join(out) + '</p>'


def entry(it):
    date = datetime.date.fromisoformat(it['date']).strftime('%-d %B %Y')
    imgs = ''.join(f'<img src="{html.escape(s)}" alt="" loading="lazy">' for s in it['images'])
    body = ''.join(para(p) for p in it['paragraphs'])
    return (f'<li><details class="writing" id="{it["slug"]}" lang="th">'
            f'<summary>{html.escape(it["title"])} <small>{date}</small></summary>'
            f'<div class="writing-body">{imgs}{body}</div></details></li>')


def build():
    items = sorted(json.loads((ROOT / 'writings' / 'data.json').read_text()),
                   key=lambda x: x['date'], reverse=True)
    groups = []
    for year, its in itertools.groupby(items, key=lambda x: x['date'][:4]):
        rows = '\n'.join(entry(it) for it in its)
        groups.append(f'<h3 class="writing-year">{year}</h3>\n<ul>\n{rows}\n</ul>')
    block = ('<!-- writings:start (generated by writings/build.py from writings/data.json) -->\n'
             + '\n'.join(groups) + '\n<!-- writings:end -->')
    page = ROOT / 'index.html'
    s = page.read_text()
    new, n = re.subn(r'<!-- writings:start.*?<!-- writings:end -->', lambda _: block, s, flags=re.S)
    if n != 1:
        raise SystemExit('writings markers not found in index.html')
    page.write_text(new)
    print(f'{len(items)} writings in {len(groups)} years')


if __name__ == '__main__':
    build()
